#ifndef _I2C_
#define _I2C_
#include "mcu.h"
//============================================================================================================
//		Function
//============================================================================================================
#define NACK	0
#define ACK		1
//============================================================================================================
//		Function
//============================================================================================================
/**************************************************************************************************************
*	Name :		I2C_Init	
* Function:	初始化I2C
**************************************************************************************************************/
extern	void I2C_Init(void);

/**************************************************************************************************************
*	Name :		I2C_Start	
* Function:	发送start信号
**************************************************************************************************************/
extern	void I2C_Start(void);

/**************************************************************************************************************
*	Name :		I2C_Stop	
* Function:	发送stop信号
**************************************************************************************************************/
extern	void I2C_Stop(void);

/**************************************************************************************************************
*	Name :		I2C_RdData	
* Function:	读取数据
× Input：		Chk：应答信号
× Output:   读取到的数据
**************************************************************************************************************/
extern	uint8_t	I2C_RdData(bit	Chk);

/**************************************************************************************************************
*	Name :		I2C_TxData	
* Function:	发送单字节数据
× Input：		需要发送的数据
**************************************************************************************************************/
extern	void I2C_TxData(uint8_t	Data);
/**************************************************************************************************************
*	Name :		EP_MultiRead	
* Function:	多字节读取eeprom
* Input:		DevSel器件地址，ByteAddr通信地址，RxData存储数组，Datalength数据长度
**************************************************************************************************************/
 extern	void 	EP_MultiRead(uint8_t	DevSel,uint8_t ByteAddr,uint8_t	*RxData,uint8_t	Datalength);

/**************************************************************************************************************
*	Name :		EP_MultiWrite	
* Function:	多字节写入
* Input:		DevSel器件地址，ByteAddr通信地址，TxData写入数组，Datalength数据长度
**************************************************************************************************************/
extern	void	EP_MultiWrite(uint8_t	DevSel,uint8_t ByteAddr,uint8_t	*TxData,uint8_t	Datalength);

/**************************************************************************************************************
*	Name :		EP_WriteByte	
* Function:	单字节写入
* Input:		DevSel器件地址，ByteAddr通信地址，DataIn数据
**************************************************************************************************************/
extern	void EP_WriteByte(uint8_t	DevSel,uint8_t ByteAddr,uint8_t	DataIn);

/**************************************************************************************************************
*	Name :		EP_RdRead	
* Function:	单字节写入
* Input:		DevSel器件地址，ByteAddr通信地址
× Output:   对应地址的数据
**************************************************************************************************************/
extern	uint8_t EP_RdRead(uint8_t	DevSel,uint8_t	ByteAddr);
#endif